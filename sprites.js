// 기분 장식: 기쁨 = 왼쪽 위 반짝이, 기운 없음 = 오른쪽 위 Z
const SPARK = [[2, 1], [1, 2], [2, 2], [3, 2], [2, 3], [13, 2]];
const ZZZ = [[12, 0], [13, 0], [14, 0], [13, 1], [12, 2], [13, 2], [14, 2]];

// 켜진 픽셀 좌표 목록. 기운 없으면 눈의 아랫줄만 그려서 감은 눈으로
function petPixels(stage, mood) {
  const rows = SPRITES[stage];
  const px = [];
  rows.forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c === '.') return;
      if (c === 'o' && mood === 'tired' && rows[y - 1][x] !== 'o') return;
      px.push([x, y]);
    });
  });
  if (stage === 'egg') return px;
  return px.concat(mood === 'happy' ? SPARK : mood === 'tired' ? ZZZ : []);
}

function petSvg(stage, mood) {
  const rects = petPixels(stage, mood).map(([x, y]) => `<rect x="${x}" y="${y}" width="1" height="1"/>`).join('');
  return `<svg class="sprite" viewBox="0 0 16 16" shape-rendering="crispEdges" fill="currentColor" role="img" aria-label="캐릭터">${rects}</svg>`;
}

if (typeof module !== 'undefined') module.exports = { SPRITES, petPixels, petSvg };
